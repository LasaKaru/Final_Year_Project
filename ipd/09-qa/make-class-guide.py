"""Builds class-guide.md: every class/record/interface in src/ with the purpose taken from its own /// <summary> doc comment.
Usage (repository root): python3 ipd/09-qa/make-class-guide.py  → ipd/09-qa/class-guide.md
It is a study checklist for risk R6 (the owner must be able to explain every class); it only reads source files."""
import html
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
DECL = re.compile(r'^\s*(?:\[[^\]]*\]\s*)*(?:public|internal)\s+(?:(?:sealed|static|abstract|partial|readonly)\s+)*'
                  r'(class|record|interface|enum|struct)\s+(?:class\s+|struct\s+)?(\w+)')

def summary(lines, i):
    """Text of the /// block directly above line i (attributes skipped)."""
    j = i - 1
    while j >= 0 and lines[j].strip().startswith("["):
        j -= 1
    block = []
    while j >= 0 and lines[j].strip().startswith("///"):
        block.insert(0, lines[j].strip()[3:].strip())
        j -= 1
    text = " ".join(block)
    m = re.search(r"<summary>(.*?)</summary>", text)
    text = m.group(1) if m else text
    text = re.sub(r'<see cref="([^"]+)"\s*/>', r"`\1`", text)
    text = re.sub(r'<paramref name="([^"]+)"\s*/>', r"`\1`", text)
    text = re.sub(r"<[^>]+>", "", text)
    return html.unescape(re.sub(r"\s+", " ", text)).strip()

out = ["# Class guide — what every class does (study checklist for risk R6)", "",
       "Generated by `make-class-guide.py` from the `/// <summary>` comments in `src/` — re-run after code changes.",
       "For each row: open the file, read it, and be able to explain **purpose · input · limitation** in your own words.",
       "Tick the box when you can. Enums and small records are listed for completeness.", ""]
total = 0
for project in sorted((ROOT / "src").iterdir()):
    if not project.is_dir():
        continue
    rows = []
    for f in sorted(project.rglob("*.cs")):
        if "/obj/" in f.as_posix() or "/bin/" in f.as_posix():
            continue
        lines = f.read_text(encoding="utf-8", errors="replace").splitlines()
        for i, line in enumerate(lines):
            m = DECL.match(line)
            if m:
                kind, name = m.groups()
                purpose = summary(lines, i).replace("|", "\\|") or "—"
                rows.append(f"| ☐ | `{name}` | {kind} | `{f.relative_to(ROOT).as_posix()}` | {purpose} |")
    if rows:
        total += len(rows)
        out += [f"## {project.name} ({len(rows)})", "", "| ✓ | Type | Kind | File | Purpose (from the doc comment) |",
                "|---|---|---|---|---|", *rows, ""]
out.insert(5, f"**{total} types** in {len([p for p in (ROOT / 'src').iterdir() if p.is_dir()])} projects.\n")
(ROOT / "ipd/09-qa/class-guide.md").write_text("\n".join(out), encoding="utf-8")
print(f"{total} types → ipd/09-qa/class-guide.md")
