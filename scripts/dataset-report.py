#!/usr/bin/env python3
"""Summarise recorded dataset runs (eval/runs/<date>-<mode>-<case>-<variant>) into one Markdown file, and write
blind labelling worksheets for cases that have no labels yet.

    python3 scripts/dataset-report.py                  # → eval/results/summary-<mode>.md
    python3 scripts/dataset-report.py --mode hybrid
    python3 scripts/dataset-report.py --worksheets     # also (re)write eval/labels/worksheets/<case>-<variant>.csv

Labels come from eval/labels/<case>-<variant>.labels.json (verified, frozen) or, if missing,
eval/labels/drafts/ (marked "draft" in the output). Worksheets list every endpoint with an id-like parameter WITHOUT
the tool's verdict, so the human rater labels blind (protocol in eval/labels/worksheets/README.md).
Standard library only; nothing here touches the network.
"""
import argparse, csv, glob, gzip, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RANK = {"OutOfScope": 0, "Protected": 1, "Unknown": 2, "Vulnerable": 3}


def unit_key(verb, route):
    r = re.sub(r"\{\s*\*{0,2}([A-Za-z0-9_]+)[^}]*\}", lambda m: "{" + m.group(1) + "}", route.strip())
    return f"{verb.strip().upper()} {r.strip('/~').lower()}"


def latest_run(mode, case_id, variant):
    # only completed runs (env.md is written last by run-case.sh)
    runs = sorted(r for r in glob.glob(os.path.join(ROOT, "eval", "runs", f"*-{mode}-{case_id}-{variant}"))
                  if os.path.exists(os.path.join(r, "env.md")))
    return runs[-1] if runs else None


def load_report(run):
    gz = os.path.join(run, "report.json.gz")
    return json.load(gzip.open(gz, "rt")) if os.path.exists(gz) else json.load(open(os.path.join(run, "report.json")))


def labels_for(case_id, variant):
    for sub, status in (("", "verified"), ("drafts", "draft")):
        p = os.path.join(ROOT, "eval", "labels", sub, f"{case_id}-{variant}.labels.json")
        if os.path.exists(p):
            return json.load(open(p)), status
    return None, None


def predictions(report, symbolic=True):
    pred = {}
    for f in report["findings"]:
        e = f["path"]["endpoint"]
        k = unit_key(e["verb"], e["routeTemplate"])
        status = f["symbolic"]["status"] if symbolic else f["final"]
        if k not in pred or RANK[status] > RANK[pred[k][0]]:
            pred[k] = (status, ",".join(f["symbolic"]["ruleIds"]))
    return pred


def outcome(label, predicted):
    if label not in ("Vulnerable", "Protected"):
        return "excluded"
    if predicted is None:
        return "no prediction"
    if predicted == "Unknown":
        return "abstained"
    flagged = predicted == "Vulnerable"
    return {("Vulnerable", True): "TP", ("Vulnerable", False): "FN", ("Protected", True): "FP", ("Protected", False): "TN"}[(label, flagged)]


def fmt(x):
    return "n/a" if x is None else f"{x:.3f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", default="symbolic")
    ap.add_argument("--worksheets", action="store_true")
    a = ap.parse_args()
    cases = json.load(open(os.path.join(ROOT, "eval", "datasets", "cases.json")))["cases"]
    out = [f"# Dataset runs — {a.mode} arm\n",
           "Generated by `scripts/dataset-report.py` from the latest recorded run of every case. "
           "Labels marked *draft* are derived from vendor fixes and still need the owner's verification. "
           "BolaLab (development set) is reported separately and never mixed in.\n"]
    totals = {}
    rows, cov, pairs = [], [], {}
    for c in cases:
        for variant in c["variants"]:
            run = latest_run(a.mode, c["caseId"], variant)
            if run is None:
                cov.append(f"| {c['caseId']} | {variant} | — | not run | | | | | | |")
                continue
            report = load_report(run)
            cv, ri = report["coverage"], report["run"]
            cov.append(f"| {c['caseId']} | {variant} | `{c['variants'][variant][:8]}` | {cv['endpoints']} | {cv['endpointsWithIdParams']} "
                       f"| {cv['symbolicVulnerable']} / {cv['symbolicProtected']} / {cv['symbolicUnknown']} / {cv['symbolicOutOfScope']} "
                       f"| {cv['projectsLoaded']} ({cv['projectsFailed']} with errors) | {ri['totalSeconds']:.1f} s "
                       f"| {ri['peakWorkingSetBytes'] // 1048576} MB | `{os.path.relpath(run, ROOT)}` |")
            labels, status = labels_for(c["caseId"], variant)
            pred = predictions(report, symbolic=(a.mode == "symbolic"))
            if labels is None:
                if a.worksheets:
                    write_worksheet(c, variant, report)
                continue
            # patched commits of Dataset A cases are the Dataset C controls: reported separately
            ds = "C (fixed commits of A)" if c["dataset"] == "A" and variant == "fixed" else c["dataset"]
            for l in labels:
                k = unit_key(l["verb"], l["route"])
                p = pred.get(k)
                o = outcome(l["label"], p[0] if p else None)
                totals.setdefault(ds, {}).setdefault(o, 0)
                totals[ds][o] += 1
                if l["label"] == "Vulnerable" and o in ("abstained", "no prediction"):
                    totals[ds]["missedVuln"] = totals[ds].get("missedVuln", 0) + 1
                rows.append(f"| {c['caseId']} | {variant} | `{k}` | {l['label']} ({status}) | {p[0] if p else '—'} | {p[1] if p else ''} | {o} |")
                pairs.setdefault((c["caseId"], k), {})[variant] = o

    out += ["## Coverage, runtime, memory\n",
            "| Case | Variant | Commit | Endpoints | With ids | V / P / U / OoS | Projects | Time | Peak RAM | Run |",
            "|---|---|---|---|---|---|---|---|---|---|", *cov, ""]
    out += ["## Labelled units\n", "| Case | Variant | Unit | Label | Predicted | Rules | Outcome |", "|---|---|---|---|---|---|---|", *rows, ""]
    out += ["## Metrics per dataset (labelled units only; Unknown = abstained, counted as a miss in operational recall)\n",
            "| Dataset | TP | FP | FN | TN | Abstained | Precision | Recall | Op. recall | FPR |", "|---|---|---|---|---|---|---|---|---|---|"]
    for ds, t in sorted(totals.items()):
        tp, fp, fn, tn, ab = (t.get(x, 0) for x in ("TP", "FP", "FN", "TN", "abstained"))
        prec = tp / (tp + fp) if tp + fp else None
        rec = tp / (tp + fn) if tp + fn else None
        vuln_total = tp + fn + t.get("missedVuln", 0)
        oprec = tp / vuln_total if vuln_total else None
        fpr = fp / (fp + tn) if fp + tn else None
        out.append(f"| {ds} | {tp} | {fp} | {fn} | {tn} | {ab} | {fmt(prec)} | {fmt(rec)} | {fmt(oprec)} | {fmt(fpr)} |")
    discriminated = [(cid, k) for (cid, k), v in pairs.items() if v.get("vuln") == "TP" and v.get("fixed") == "TN"]
    pair_total = [(cid, k) for (cid, k), v in pairs.items() if "vuln" in v and "fixed" in v and
                  v.get("vuln") in ("TP", "FN", "abstained") and v.get("fixed") in ("TN", "FP", "abstained")]
    out += ["", f"**Vulnerable→fixed pairs discriminated** (flagged before the fix, passed after it): "
                f"{len(discriminated)} of {len(pair_total)} — " + ", ".join(f"{cid} `{k}`" for cid, k in discriminated), ""]
    os.makedirs(os.path.join(ROOT, "eval", "results"), exist_ok=True)
    path = os.path.join(ROOT, "eval", "results", f"summary-{a.mode}.md")
    open(path, "w").write("\n".join(out) + "\n")
    print(f"wrote {os.path.relpath(path, ROOT)}")


def write_worksheet(c, variant, report):
    d = os.path.join(ROOT, "eval", "labels", "worksheets")
    os.makedirs(d, exist_ok=True)
    seen = {}
    for f in report["findings"]:
        e = f["path"]["endpoint"]
        k = unit_key(e["verb"], e["routeTemplate"])
        if k in seen:
            continue
        a = e["authorization"]
        loc = e.get("location") or {}
        seen[k] = {
            "unit": k, "action": f"{e['controller']}.{e['action']}",
            "file": f"{loc.get('filePath', '')}:{loc.get('startLine', '')}",
            "authorize": "anonymous" if a.get("allowAnonymous") else ("yes" if a.get("hasAuthorize") else "no/global"),
            "roles": ";".join(a.get("roles") or []), "policies": ";".join(a.get("policies") or []),
            "id_parameters": ";".join(p["name"] for p in e["parameters"] if p.get("isIdLike")),
            "q1_client_id_selects_object": "", "q2_cross_user_effect": "", "q3_owner_check_before_effect": "",
            "label": "", "notes": "", "rater": "", "date": "",
        }
    path = os.path.join(d, f"{c['caseId']}-{variant}.csv")
    with open(path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(next(iter(seen.values())).keys()) if seen else ["unit"])
        w.writeheader()
        for k in sorted(seen):
            w.writerow(seen[k])
    print(f"wrote {os.path.relpath(path, ROOT)} ({len(seen)} units)")


if __name__ == "__main__":
    sys.exit(main())
